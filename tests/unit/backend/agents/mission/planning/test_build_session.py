class TestRefinementMode:
    def test_seeds_from_existing_plan(self):
        t1, t2 = generate_task_id(), generate_task_id()
        existing = {
            "tasks": [
                {
                    "task_id": t1,
                    "agent": SCANNER,
                    "description": "Scan",
                    "instructions": "Run scanners",
                },
                {"task_id": t2, "agent": TRIAGE, "description": "Triage", "instructions": "Filter"},
            ]
        }
        s = _session(current_plan=existing)
        # Seeded UUIDs are preserved — stable ids across refinements
        assert set(s.tasks) == {t1, t2}

    def test_new_tasks_get_fresh_uuid_ids(self):
        t1 = generate_task_id()
        existing = {
            "tasks": [
                {"task_id": t1, "agent": SCANNER, "description": "Scan", "instructions": "X"},
            ]
        }
        s = _session(current_plan=existing)
        new_id = _add(s, description="New", agent=TRIAGE)
        assert _is_uuid(new_id)
        assert new_id != t1
        assert set(s.tasks) == {t1, new_id}


