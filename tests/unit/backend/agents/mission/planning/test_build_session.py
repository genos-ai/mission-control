class TestFinalise:
    def _build_wasa_plan(self, s: PlanBuildingSession) -> list[str]:
        """Build a 3-task scan -> triage -> report chain. Returns task ids."""
        t1 = _add(
            s,
            description="Scan",
            agent=SCANNER,
            instructions="Run scanners",
            domain_tags=["security"],
        )
        t2 = _add(
            s, description="Triage", agent=TRIAGE, instructions="Filter FPs", dependencies=[t1]
        )
        t3 = _add(
            s,
            description="Report",
            agent=REPORTER,
            instructions="Write report",
            dependencies=[t2],
        )
        return [t1, t2, t3]

    def test_valid_plan_passes(self):
        s = _session()
        task_ids = self._build_wasa_plan(s)
        result = s.finalise(
            summary="WASA scan", estimated_cost_usd=5.0, estimated_duration_seconds=120
        )
        assert result["valid"] is True
        assert s.finalised_plan is not None
        assert len(s.finalised_plan["tasks"]) == 3
        # Finalised task ids match the generated UUIDs, order preserved
        assert [t["task_id"] for t in s.finalised_plan["tasks"]] == task_ids

    def test_empty_plan_fails(self):
        s = _session()
        result = s.finalise(summary="Empty", estimated_cost_usd=0, estimated_duration_seconds=0)
        assert result["valid"] is False
        assert "no tasks" in result["errors"][0].lower()

    def test_cycle_detected(self):
        s = _session()
        t1 = _add(s, description="A", agent=SCANNER)
        t2 = _add(s, description="B", agent=TRIAGE, dependencies=[t1])
        # Manually create a cycle
        s.tasks[t1]["dependencies"] = [t2]
        result = s.finalise(summary="Cycle", estimated_cost_usd=1, estimated_duration_seconds=60)
        assert result["valid"] is False
        assert any("cycle" in e.lower() for e in result["errors"])

    def test_legacy_task_id_format_rejected(self):
        """Plan 72: v{N}-task-{NNN} ids are no longer valid — UUIDs only."""
        s = _session()
        t1 = _add(s, description="A", agent=SCANNER)
        s.tasks[t1]["task_id"] = "v1-task-001"
        result = s.finalise(summary="Legacy", estimated_cost_usd=1, estimated_duration_seconds=60)
        assert result["valid"] is False
        assert any("must be a valid UUID" in e for e in result["errors"])

    def test_negative_cost_fails(self):
        s = _session()
        self._build_wasa_plan(s)
        result = s.finalise(summary="Bad", estimated_cost_usd=-1.0, estimated_duration_seconds=60)
        assert result["valid"] is False


