"""Unit tests for PlanBuildingSession — incremental plan assembly.

Plan 72 contract: task_ids are UUID strings generated by the session
(no more v{N}-task-{NNN} prefixes). Tests capture the returned ids and
assert UUID validity, uniqueness, and linkage rather than literal ids.
"""

from uuid import UUID, uuid4

from modules.backend.agents.mission.planning.build_session import (
    PlanBuildingSession,
    generate_task_id,
    semantic_check,
)
from modules.backend.agents.mission_control.roster import (
    Roster,
    RosterAgentEntry,
    RosterConstraintsSchema,
    RosterInterfaceSchema,
    RosterModelSchema,
)
from modules.backend.schemas.task_plan import TaskPlan

SCANNER = "security.webapp.scanner.agent"
TRIAGE = "security.webapp.triage.agent"
REPORTER = "security.webapp.reporter.agent"


def _entry(name: str, version: str = "1.0.0") -> RosterAgentEntry:
    return RosterAgentEntry(
        agent_name=name,
        agent_version=version,
        description=f"Test agent {name}",
        model=RosterModelSchema(name="test:model"),
        interface=RosterInterfaceSchema(),
        constraints=RosterConstraintsSchema(),
    )


def _roster(*names: str) -> Roster:
    return Roster(agents=[_entry(n) for n in names])


WASA_ROSTER = _roster(SCANNER, TRIAGE, REPORTER)


def _session(**kwargs) -> PlanBuildingSession:
    defaults = {
        "mission_id": "test-001",
        "version": 1,
        "roster": WASA_ROSTER,
        "budget_usd": 10.0,
    }
    defaults.update(kwargs)
    return PlanBuildingSession(**defaults)


def _is_uuid(value: str) -> bool:
    try:
        UUID(value)
    except (TypeError, ValueError):
        return False
    return True


def _add(
    s: PlanBuildingSession,
    *,
    agent: str = SCANNER,
    description: str = "Task",
    instructions: str = "Do it",
    **kwargs,
) -> str:
    """Add a task and return its generated UUID task_id."""
    result = s.add_task(description=description, agent=agent, instructions=instructions, **kwargs)
    assert "error" not in result, result
    return result["task_id"]


class TestAddTask:
    def test_adds_task_with_generated_uuid_id(self):
        s = _session()
        result = s.add_task(
            description="Scan codebase",
            agent=SCANNER,
            instructions="Run all scanners",
        )
        assert _is_uuid(result["task_id"])
        assert result["status"] == "proposed"
        assert result["task_id"] in s.tasks
        assert s.tasks[result["task_id"]]["task_id"] == result["task_id"]

    def test_ids_are_unique_uuids(self):
        s = _session()
        t1 = _add(s, description="A", agent=SCANNER)
        t2 = _add(s, description="B", agent=TRIAGE)
        assert t1 != t2
        assert _is_uuid(t1) and _is_uuid(t2)
        assert set(s.tasks) == {t1, t2}

    def test_rejects_unknown_agent(self):
        s = _session()
        result = s.add_task(
            description="Bad",
            agent="nonexistent.agent",
            instructions="X",
        )
        assert "error" in result
        assert "not found in roster" in result["error"]

    def test_rejects_unknown_dependency(self):
        s = _session()
        result = s.add_task(
            description="Bad",
            agent=SCANNER,
            instructions="X",
            dependencies=[str(uuid4())],
        )
        assert "error" in result
        assert "not found in plan" in result["error"]

    def test_valid_dependency(self):
        s = _session()
        t1 = _add(s, description="A", agent=SCANNER)
        r2 = s.add_task(
            description="B",
            agent=TRIAGE,
            instructions="B",
            dependencies=[t1],
        )
        assert "error" not in r2
        assert s.tasks[r2["task_id"]]["dependencies"] == [t1]

    def test_domain_tags(self):
        s = _session()
        t1 = _add(s, description="A", agent=SCANNER, domain_tags=["security", "scan"])
        assert s.tasks[t1]["domain_tags"] == ["security", "scan"]


